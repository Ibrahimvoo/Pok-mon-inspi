# Traces the dead body of the reference in-game screenshot (pink player "Cass" and her body) into
# colour-keyed shapes, at the scale of the traced crewmate base (crewmate-ref.js) and facing right like it.
# Usage: python3 -I tools/among/trace_ghost_body.py screenshot.jpg out.js
import sys, json
import numpy as np, cv2
from PIL import Image

src, out = sys.argv[1], sys.argv[2]
UP = 8                                   # work on an 8× Lanczos upscale for smooth contours
full = Image.open(src).convert('RGB')

def crop(box):
    c = full.crop(box)
    return np.array(c.resize((c.width * UP, c.height * UP), Image.LANCZOS)).astype(int)
def clean(m, k=5):
    m = m.astype(np.uint8)
    m = cv2.morphologyEx(m, cv2.MORPH_OPEN, np.ones((k, k), np.uint8))
    return cv2.morphologyEx(m, cv2.MORPH_CLOSE, np.ones((k, k), np.uint8)).astype(bool)
def disk(R): yy, xx = np.mgrid[-R:R + 1, -R:R + 1]; return ((xx ** 2 + yy ** 2) <= R * R).astype(np.uint8)
def biggest(m):
    n, cc, st, _ = cv2.connectedComponentsWithStats(m.astype(np.uint8), 8)
    if n <= 1: return m
    i = 1 + int(np.argmax(st[1:, 4])); return cc == i
def fill_holes(m):
    cs, _ = cv2.findContours(m.astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    f = np.zeros(m.shape, np.uint8); cv2.drawContours(f, cs, -1, 1, -1); return f.astype(bool)
def poly(m, scale, ox, oy, W, flip):
    cs, _ = cv2.findContours(m.astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    res = []
    for c in cs:
        if cv2.contourArea(c) < 80: continue
        pts = c[:, 0, :].astype(float)
        k = 6; pad = np.concatenate([pts[-k:], pts, pts[:k]])
        sm = np.array([pad[i:i + 2 * k + 1].mean(axis=0) for i in range(len(pts))])
        ap = cv2.approxPolyDP(sm.astype(np.float32).reshape(-1, 1, 2), 1.2, True)[:, 0, :]
        res.append([[round(((W - x) if flip else x) * scale + ox, 1), round(y * scale + oy, 1)] for x, y in ap])
    return res

# The ghost is translucent in the screenshot (the background shows through), so it is not segmented here: its
# upper part is the crewmate base and its tail outline is read from the screenshot (crew.js, GHOST_TAIL).
# Scale: width of the ghost's visor in the screenshot (26.4 px) ↔ width of the base visor.
vis_w = 26.4 * UP
# ------------------------------------------------------------------ dead body
d = crop((133, 205, 200, 270))
r, gg, b = d[..., 0], d[..., 1], d[..., 2]
mx = np.maximum(np.maximum(r, gg), b)
purple = (b > gg + 25) & (r > gg + 20)
main = purple & (mx > 170)
shade = purple & (mx > 120) & (mx <= 170)
deep = purple & (mx > 70) & (mx <= 120)
bone = (r > 140) & (gg > 140) & (b > 140) & (abs(r - b) < 40)
bone_dark = (r > 120) & (gg > 120) & (b > 120) & ~bone
stuff = clean(main | shade | deep | bone, 7)
blob = biggest(cv2.morphologyEx(stuff.astype(np.uint8), cv2.MORPH_CLOSE, disk(4 * UP)).astype(bool))
dsil = fill_holes(cv2.dilate(blob.astype(np.uint8), disk(int(1.6 * UP))).astype(bool))
# the body is a closed rounded shape (the dark cut is inside it): use the convex hull of its outline
hull = cv2.convexHull(cv2.findNonZero(dsil.astype(np.uint8)))
dsil = np.zeros(dsil.shape, np.uint8); cv2.fillPoly(dsil, [hull], 1); dsil = dsil.astype(bool)

# ------------------------------------------------------------------ scale to the crewmate base
sys.path.insert(0, '')
ref = open('src/among/art/crewmate-ref.js').read()
REF = json.loads(ref.split('export const REF = ')[1].split(';\n')[0])
SH = json.loads(ref.split('export const SHAPES = ')[1].split(';\n')[0])
def bb(list_):
    xs = [p[0] for poly_ in list_ for p in poly_]; ys = [p[1] for poly_ in list_ for p in poly_]
    return min(xs), min(ys), max(xs), max(ys)
vx0, vy0, vx1, vy1 = bb(SH['visor'])
scale = (vx1 - vx0) / vis_w                      # reference pixels per upscaled screenshot pixel
# body: same scale; feet line at the base's feet, centred on the base centre
Hd, Wd = dsil.shape
ys, xs = np.where(dsil)
bx = REF['center'] - ((xs.min() + xs.max()) / 2) * scale
by = REF['feet'] - ys.max() * scale
P = lambda m: poly(m & dsil, scale, bx, by, Wd, False)
dead = { 'sil': poly(dsil, scale, bx, by, Wd, False), 'inner': P(cv2.erode(dsil.astype(np.uint8), disk(int(1.4 * UP))).astype(bool)), 'deep': P(clean(deep | shade | main, 5)), 'shade': P(clean(shade | main, 5)), 'main': P(clean(main, 5)),
         'bone': P(clean(bone | bone_dark, 5)), 'boneLight': P(clean(bone, 5)) }
ys, xs = np.where(dsil)
dead_meta = { 'top': round(float(ys.min() * scale + by), 1), 'w': round(float((xs.max() - xs.min()) * scale), 1) }
with open(out, 'w') as f:
    f.write('// Generated by tools/among/trace_ghost_body.py from the in-game reference screenshot: do not edit by hand.\n')
    f.write('// Same coordinate system as crewmate-ref.js (reference pixels, facing right).\n')
    f.write('export const DEAD = ' + json.dumps({ **dead, **dead_meta }, separators=(',', ':')) + ';\n')
print('scale', round(scale, 3), dead_meta, {k: [len(p) for p in v] for k, v in dead.items()})
dbg = np.zeros(dsil.shape + (3,), np.uint8); dbg[dsil] = (30, 30, 30)
for m, c in [(deep, (100, 40, 110)), (shade, (160, 50, 170)), (main, (235, 90, 200)), (bone_dark, (160, 160, 160)), (bone, (250, 250, 250))]: dbg[m & dsil] = c
Image.fromarray(dbg).save(out + '.dead.png')

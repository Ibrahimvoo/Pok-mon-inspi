def check(ref, out, n):
  from PIL import Image, ImageDraw
  P = PLAN[n]
  im = Image.open(ref).convert('RGB').resize((2000, 924))
  ov = Image.new('RGBA', im.size, (0, 0, 0, 0)); d = ImageDraw.Draw(ov)
  if 'ground' in P: d.polygon(P['ground'], fill=(255, 255, 0, 50), outline=(255, 255, 0, 255), width=2)
  for h in P['halls'] + P.get('pale', []): d.polygon(h, fill=(255, 0, 0, 90), outline=(255, 0, 0, 255), width=2)
  for k in ('shell', 'ship'):
    if k in P: d.polygon(P[k], outline=(0, 255, 255, 255), width=2)
  for r in P['rooms'].values(): d.polygon(r, fill=(0, 255, 0, 70), outline=(0, 255, 0, 255), width=2)
  im = im.convert('RGBA'); im.alpha_composite(ov); im.convert('RGB').save(out)
if sys.argv[1] == 'check': check(sys.argv[2], sys.argv[3], sys.argv[4])
def centroid(P):
  a = cx = cy = 0
  for (x0, y0), (x1, y1) in zip(P, P[1:] + P[:1]):
    c = x0 * y1 - x1 * y0; a += c; cx += (x0 + x1) * c; cy += (y0 + y1) * c
  return (cx / (3 * a), cy / (3 * a))
def js(world, out):
  W = json.load(open(world)); data = {}
  for n, P in PLAN.items():
    src, dst = [], []
    for r in W[n]['rooms']:
      poly = P['rooms'].get(r['name']) or (P.get('ship') if r['name'] == 'Navette' else None)
      if not poly or not r['c']: continue
      src.append(r['c']); dst.append(centroid(poly))
    def fit(i):
      xs = [s[i] for s in src]; ys = [d[i] for d in dst]; m = len(xs); mx = sum(xs) / m; my = sum(ys) / m
      k = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs); return k, my - k * mx
    (kx, bx), (ky, by) = fit(0), fit(1)
    anchors = [[round(s[0], 2), round(s[1], 2), round(d[0] - (kx * s[0] + bx), 1), round(d[1] - (ky * s[1] + by), 1)] for s, d in zip(src, dst)]
    print(n, 'max residual', max(max(abs(a[2]), abs(a[3])) for a in anchors))
    pts = [p for poly in list(P['rooms'].values()) + P['halls'] + [P.get('ground', [])] + [P.get('shell', [])] for p in poly]
    box = [min(p[0] for p in pts) - 12, min(p[1] for p in pts) - 12, max(p[0] for p in pts) + 12, max(p[1] for p in pts) + 12]
    data[n] = {'box': box, 'kx': round(kx, 4), 'bx': round(bx, 2), 'ky': round(ky, 4), 'by': round(by, 2), 'anchors': anchors,
      'rooms': list(P['rooms'].values()), 'halls': P['halls'], 'pale': P.get('pale', []), 'ground': P.get('ground'), 'pins': P.get('pins', []),
      'shell': P.get('shell'), 'ship': P.get('ship'), 'dash': P.get('dash'), 'labels': [[k, x, y, k in P['small']] for k, (x, y) in P['labels'].items()]}
  open(out, 'w').write('// In-game map overlay traced by hand on the reference screenshots (tools/among/minimap_plan.py, 2000×924\n'
    '// screen coordinates) and the mapping world units -> those coordinates fitted on the room centres.\nexport const MINIMAP = ' + json.dumps(data, separators=(',', ':')) + ';\n')
if sys.argv[1] == 'js': js(sys.argv[2], sys.argv[3])
